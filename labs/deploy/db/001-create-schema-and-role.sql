-- Owner script: creates the restricted application role and its schema.
-- Run once as a privileged user (Postgres superuser or Supabase postgres). Idempotent.
--
-- What it does:
--   * role lf_app: login, not a superuser, NO password in this file
--   * schema learning_factory: lf_app may use it and create objects in it
--   * revokes lf_app's OWN grants on schema public (it can no longer create there)
--   * lf_app's default search_path is learning_factory
--
-- What this does NOT restrict: rights that lf_app holds through the PUBLIC pseudo-role.
-- Revoking from lf_app does not remove those. Unless PUBLIC's rights are tightened, lf_app
-- still has USAGE on schema public, EXECUTE on functions in public, CONNECT and TEMP on
-- the database, and read access to pg_catalog. Tightening PUBLIC is the owner's decision,
-- because the database is shared with another app and this script must not change what
-- that app relies on.
--
-- The owner sets the password separately, never in this file:
--   alter role lf_app password '<generated by the owner>';
-- The manager's migrations (labs/manager/migrations) run as lf_app inside this schema only.

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'lf_app') then
    create role lf_app login;
  else
    alter role lf_app login;
  end if;
end
$$;

create schema if not exists learning_factory;
grant usage, create on schema learning_factory to lf_app;
revoke all on schema public from lf_app;
alter role lf_app set search_path = learning_factory;
